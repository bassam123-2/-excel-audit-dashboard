from __future__ import annotations

LOCALES = frozenset({"en", "ar"})


def normalize_locale(locale: str | None) -> str:
    if not locale:
        return "en"
    loc = str(locale).strip().lower().replace("_", "-")
    if loc.startswith("ar"):
        return "ar"
    return "en"


def tr(locale: str, key: str, **kwargs: str | int | float) -> str:
    loc = normalize_locale(locale)
    s = STRINGS.get(loc, {}).get(key) or STRINGS["en"].get(key, key)
    if kwargs:
        return s.format(**kwargs)
    return s


